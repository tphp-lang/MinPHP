<?php

declare(strict_types=1);

namespace Tphp\Gen;

use Tphp\Ast\decl\ClassDecl;
use Tphp\Ast\decl\EnumDecl;
use Tphp\Ast\decl\FunctionDecl;
use Tphp\Ast\File;
use Tphp\Table\ClassSymbol;
use Tphp\Table\FnSymbol;
use Tphp\Table\InterfaceSymbol;
use Tphp\Table\VarSymbol;
use Tphp\Type\Type;

/** 声明生成：类型/全局/原型/函数体/入口 main。 */
trait GenDeclTrait
{
    /** 是否最后一条语句为 return（补零值返回用）。 */
    private bool $lastReturned = false;

    /** 当前函数返回类型（return 接口包装 / or 传播零值用）。 */
    private int $curRet = 0;

    /** 当前函数是否插深度保护（调用环检测收敛；闭包恒 true——thunk 静态不可分析）。 */
    private bool $curDepthGuard = true;

    /**
     * 收集生成工作项：[FnSymbol, body, 所属类(方法)或 null(全局函数)]。
     *
     * @param list<File> $files
     * @return list<array{FnSymbol, array, ?ClassSymbol}>
     */
    private function collectDecls(array $files): array
    {
        $items = [];
        foreach ($files as $file) {
            $prefix = $file->namespace !== '' ? $file->namespace . '\\' : '';
            foreach ($file->decls as $decl) {
                if ($decl instanceof FunctionDecl) {
                    $fn = $this->table->fns[$prefix . $decl->name] ?? null;
                    if ($fn !== null) {
                        $items[] = [$fn, $decl->body, null];
                    }
                    continue;
                }
                if ($decl instanceof ClassDecl) {
                    $class = $this->table->classes[$prefix . $decl->name] ?? null;
                    if ($class === null) {
                        continue;
                    }
                    foreach ($decl->methods as $method) {
                        $fn = $class->methods[$method->name] ?? null;
                        if ($fn !== null) {
                            $items[] = [$fn, $method->body, $class];
                        }
                    }
                }
                if ($decl instanceof EnumDecl) {
                    $class = $this->table->classes[$prefix . $decl->name] ?? null;
                    if ($class === null) {
                        continue;
                    }
                    foreach ($decl->methods as $method) {
                        $fn = $class->methods[$method->name] ?? null;
                        if ($fn !== null) {
                            $items[] = [$fn, $method->body, $class];
                        }
                    }
                }
            }
        }
        return $items;
    }

    /** @return list<ClassSymbol> 父类在前 */
    private function classesTopo(): array
    {
        $out = [];
        $seen = [];
        $visit = static function (ClassSymbol $c) use (&$visit, &$out, &$seen): void {
            if (isset($seen[$c->name])) {
                return;
            }
            $seen[$c->name] = true;
            if ($c->parent !== null) {
                $visit($c->parent);
            }
            $out[] = $c;
        };
        foreach ($this->table->classes as $class) {
            $visit($class);
        }
        return $out;
    }

    private function findMethodSym(ClassSymbol $class, string $name): ?FnSymbol
    {
        return $class->findMethod($name);
    }

    /** 实际生效的构造器：沿继承链向上找 __construct。 @return array{FnSymbol, ClassSymbol}|null */
    private function effectiveCtor(ClassSymbol $class): ?array
    {
        for ($c = $class; $c !== null; $c = $c->parent) {
            $fn = $c->methods['__construct'] ?? null;
            if ($fn !== null) {
                return [$fn, $c];
            }
        }
        return null;
    }

    /** C 参数列表（不含 self）。 */
    private function paramListC(FnSymbol $fn): string
    {
        $parts = [];
        foreach ($fn->params as $param) {
            $parts[] = $this->cType($param->type) . ' ' . Names::localVar($param->name);
        }
        return implode(', ', $parts);
    }

    // ------------------------------------------------------------------ 类型

    private function emitHead(): void
    {
        $this->begin('head');
        $this->w('/* Generated by TinyPHP 0.3 — DO NOT EDIT */');
        $this->w('#include "prelude.h"');
        $this->w('');
    }

    /** 常量 → C 宏（与旧版机制一致：TPHP_CONST_<UPPER> / TPHP_CONST_<CLASS>_<UPPER>）。 */
    /** #include 指令：输出到头区（常量宏之前，供 cconst/cstruct 引用）。 */
    private function emitIncludes(array $files): void
    {
        $this->begin('consts');
        $emitted = [];
        foreach ($files as $file) {
            foreach ($file->includes as $inc) {
                if (isset($emitted[$inc])) {
                    continue;
                }
                $emitted[$inc] = true;
                // 带 / 的视为相对路径头文件，其余按系统头文件输出
                $this->w(str_contains($inc, '/') ? '#include "' . trim($inc, '"<>') . '"' : '#include ' . $inc);
            }
        }
        if ($emitted !== []) {
            $this->w('');
        }
    }

    private function emitConsts(): void
    {
        $this->begin('consts');
        foreach ($this->table->consts as $const) {
            $this->w('#define ' . Names::constMacro($const->name) . ' ' . $this->genExpr($const->value));
        }
        foreach ($this->classesTopo() as $class) {
            foreach ($class->consts as $const) {
                $this->w('#define ' . Names::classConstMacro($const->owner->name, $const->name) . ' ' . $this->genExpr($const->value));
            }
        }
        if ($this->table->consts !== [] || $this->classesHaveConsts()) {
            $this->w('');
        }
    }

    private function classesHaveConsts(): bool
    {
        foreach ($this->table->classes as $class) {
            if ($class->consts !== []) {
                return true;
            }
        }
        return false;
    }

    /** @param list<array{FnSymbol, array, ?ClassSymbol}> $items */
    private function emitTypes(array $items): void
    {
        $classes = $this->classesTopo();

        $this->begin('typedefs');
        if ($classes !== []) {
            foreach ($classes as $class) {
                $struct = Names::classStruct($class->name);
                $this->w('typedef struct ' . $struct . ' ' . $struct . ';');
                if ($class->vtableOrder !== []) {
                    $vt = Names::vtableType($class->name);
                    $this->w('typedef struct ' . $vt . ' ' . $vt . ';');
                }
            }
            $this->w('');
            foreach ($classes as $class) {
                $this->emitVtableStruct($class);
            }
            $this->w('');
            foreach ($classes as $class) {
                $this->emitClassStruct($class);
            }
            $this->emitInterfaceTypedefs();
        }

        $this->begin('globals');
        foreach ($classes as $class) {
            foreach ($class->props as $prop) {
                if (!$prop->isStatic) {
                    continue;
                }
                $global = Names::staticProp($class->name, $prop->name);
                $init = $prop->hasDefault ? $this->genExpr($prop->default) : $this->zeroValue($prop->type);
                $this->w('static ' . $this->cType($prop->type) . ' ' . $global . ' = ' . $init . ';');
            }
        }
    }

    /** vtable 槽位的原始声明类（保持与基类 vtable 的前缀布局兼容）。 */
    private function slotDeclaringClass(ClassSymbol $class, string $methodName): ClassSymbol
    {
        // 从最基类向下找第一个声明该方法的类
        $chain = [];
        for ($c = $class; $c !== null; $c = $c->parent) {
            array_unshift($chain, $c);
        }
        foreach ($chain as $c) {
            if (isset($c->methods[$methodName])) {
                return $c;
            }
        }
        return $class;
    }

    private function emitVtableStruct(ClassSymbol $class): void
    {
        if ($class->vtableOrder === []) {
            return;
        }
        $vt = Names::vtableType($class->name);
        $this->w('struct ' . $vt . ' {');
        $this->indent = 1;
        foreach ($class->vtableOrder as $methodName) {
            $slotClass = $this->slotDeclaringClass($class, $methodName);
            $fn = $this->findMethodSym($class, $methodName);
            $params = [$this->cType($slotClass->code) . 'self'];
            foreach ($fn->params as $param) {
                $params[] = $this->cType($param->type);
            }
            $this->w($this->cType($fn->ret) . ' (*' . $methodName . ')(' . implode(', ', $params) . ');');
        }
        $this->indent = 0;
        $this->w('};');
    }

    private function emitVtableInstance(ClassSymbol $class): void
    {
        $this->w('static const ' . Names::vtableType($class->name) . ' ' . Names::vtableInstance($class->name) . ' = {');
        $this->indent = 1;
        foreach ($class->vtableOrder as $methodName) {
            // 槽位对应的最终实现：本类或最近的父类声明（子类重写优先）。
            // 重写实现的 self 参数类型是重写类，与槽位的基类指针不同，需显式转型。
            $slotClass = $this->slotDeclaringClass($class, $methodName);
            $resolved = $this->findMethodImpl($class, $methodName);
            $cast = $this->fnPtrCast($class, $methodName, $slotClass);
            $this->w('.' . $methodName . ' = ' . $cast . $resolved . ',');
        }
        $this->indent = 0;
        $this->w('};');
        $this->w('');
    }

    /** 槽位函数指针类型的转型文本；签名一致时返回空串。 */
    private function fnPtrCast(ClassSymbol $class, string $methodName, ClassSymbol $slotClass): string
    {
        $fn = $this->findMethodSym($class, $methodName);
        $implClass = $this->findMethodImplClass($class, $methodName);
        if ($implClass->name === $slotClass->name) {
            return '';
        }
        $params = [$this->cType($slotClass->code)];
        foreach ($fn->params as $param) {
            $params[] = $this->cType($param->type);
        }
        $ret = $this->cType($fn->ret);
        return '(' . $ret . ' (*)(' . implode(', ', $params) . '))';
    }

    /** 方法实现所在的类（最近的声明/重写处）。 */
    private function findMethodImplClass(ClassSymbol $class, string $methodName): ClassSymbol
    {
        for ($c = $class; $c !== null; $c = $c->parent) {
            if (isset($c->methods[$methodName])) {
                return $c;
            }
        }
        return $class;
    }

    /** vtable 槽位对应的最终实现函数名（本类或最派生重写）。 */
    private function findMethodImpl(ClassSymbol $receiver, string $methodName): string
    {
        for ($c = $receiver; $c !== null; $c = $c->parent) {
            if (isset($c->methods[$methodName])) {
                return Names::method($c->name, $methodName);
            }
        }
        return Names::method($receiver->name, $methodName);
    }

    private function emitClassStruct(ClassSymbol $class): void
    {
        $struct = Names::classStruct($class->name);
        $this->w('struct ' . $struct . ' {');
        $this->indent = 1;
        $this->w('TPHP_OBJECT_HEAD');
        if ($class->isEnum) {
            // 枚举 case：name（全部）+ value（backed）；均为 .rodata 字面量，无堆字段
            $this->w('String name;');
            if ($class->enumBacking === Type::I_STRING) {
                $this->w('String value;');
            } elseif ($class->enumBacking === Type::I_INT) {
                $this->w('int32_t value;');
            }
            $this->indent = 0;
            $this->w('};');
            $this->w('');
            return;
        }
        // 字段平铺：继承字段按基类优先顺序展开（前缀布局与父类兼容）
        $chain = [];
        for ($c = $class; $c !== null; $c = $c->parent) {
            array_unshift($chain, $c);
        }
        foreach ($chain as $c) {
            foreach ($c->props as $prop) {
                if ($prop->isStatic) {
                    continue;
                }
                $this->w($this->cType($prop->type) . ' ' . Names::localVar($prop->name) . ';');
            }
        }
        $this->indent = 0;
        $this->w('};');
        $this->w('');
    }

    /** 接口 itab 类型（Go 风格胖指针的方法表）：父接口槽位在前（前缀布局）。 */
    private function emitInterfaceTypedefs(): void
    {
        $ifaces = $this->table->ifaces;
        if ($ifaces === []) {
            return;
        }
        foreach ($ifaces as $iface) {
            $this->w('typedef struct ' . Names::itabType($iface->name) . ' ' . Names::itabType($iface->name) . ';');
        }
        $this->w('');
        foreach ($ifaces as $iface) {
            $this->w('struct ' . Names::itabType($iface->name) . ' {');
            $this->indent = 1;
            foreach ($iface->orderedMethods() as $name => $sig) {
                $params = ['void *self'];
                foreach ($sig->params as $param) {
                    $params[] = $this->cType($param->type);
                }
                $this->w($this->cType($sig->ret) . ' (*' . $name . ')(' . implode(', ', $params) . ');');
            }
            $this->indent = 0;
            $this->w('};');
            $this->w('');
        }
    }

    /** 每 (类, 接口) 对的 itab 实例；实现来自父类时解析到最近实现并强转为 void* self。 */
    private function emitItabInstances(): void
    {
        $any = false;
        foreach ($this->classesTopo() as $class) {
            foreach ($this->classInterfaces($class) as $iface) {
                if (!$any) {
                    $this->w('/* ---- 接口 itab 实例 ---- */');
                    $any = true;
                }
                $this->w('static const ' . Names::itabType($iface->name) . ' '
                    . Names::itabInstance($class->name, $iface->name) . ' = {');
                $this->indent = 1;
                foreach ($iface->orderedMethods() as $name => $sig) {
                    $impl = $this->findMethodImpl($class, $name);
                    $params = array_merge(['void *'], array_map(
                        fn ($p) => $this->cType($p->type),
                        $sig->params,
                    ));
                    $cast = '(' . $this->cType($sig->ret) . ' (*)(' . implode(', ', $params) . '))';
                    $this->w('.' . $name . ' = ' . $cast . $impl . ',');
                }
                $this->indent = 0;
                $this->w('};');
            }
        }
        if ($any) {
            $this->w('');
        }
    }

    /** 类沿继承链实现的全部接口（含接口 extends 闭包）。 @return array<string, InterfaceSymbol> */
    private function classInterfaces(ClassSymbol $class): array
    {
        $out = [];
        for ($c = $class; $c !== null; $c = $c->parent) {
            foreach ($c->implements as $iface) {
                foreach ($iface->extendsClosure() as $name => $ancestor) {
                    $out[$name] = $ancestor;
                }
            }
        }
        return $out;
    }

    // ------------------------------------------------------------------ 原型

    /** @param list<array{FnSymbol, array, ?ClassSymbol}> $items */
    private function emitProtos(array $items): void
    {
        $this->begin('protos');
        if ($items !== []) {
            $this->w('/* ---- 函数原型 ---- */');
        }
        foreach ($items as [$fn, $body, $class]) {
            if ($class === null) {
                $this->w($this->cType($fn->ret) . ' ' . $this->fnName($fn->name) . '(' . $this->paramListC($fn) . ');');
            } else {
                $this->w($this->methodSignature($fn, $class) . ';');
            }
        }
        $classes = $this->classesTopo();
        if ($classes !== []) {
            $this->w('');
            $this->w('/* ---- 对象构造辅助 ---- */');
            foreach ($classes as $class) {
                if ($class->isEnum) {
                    $init = Names::method($class->name, '__enum_init');
                    $this->w('static void ' . $init . '(void);');
                    foreach ($class->enumCases as $c) {
                        $this->w('static ' . Names::classStruct($class->name) . '* tphp_e_' . Names::mangle($class->name) . '_' . $c['name'] . ';');
                    }
                    $struct = Names::classStruct($class->name);
                    if ($class->enumBacking !== null) {
                        $backC = $class->enumBacking === Type::I_STRING ? 'String' : 'int32_t';
                        $this->w('static ' . $struct . '* ' . Names::method($class->name, 'from') . '(' . $backC . ' value);');
                        $this->w('static ' . $struct . '* ' . Names::method($class->name, 'tryFrom') . '(' . $backC . ' value);');
                    }
                    $this->w('static Array* ' . Names::method($class->name, 'cases') . '(void);');
                    continue;
                }
                $this->w($this->newHelperSignature($class) . ';');
            }
            // vtable 实例必须在全部方法原型之后（静态初始化器引用函数地址）
            $this->w('');
            $this->w('/* ---- vtable 实例 ---- */');
            foreach ($classes as $class) {
                if ($class->vtableOrder !== []) {
                    $this->emitVtableInstance($class);
                }
            }
            $this->emitItabInstances();
        }
    }

    private function methodSignature(FnSymbol $fn, ClassSymbol $class): string
    {
        $name = Names::method($class->name, $fn->name);
        if ($fn->isStatic) {
            return $this->cType($fn->ret) . ' ' . $name . '(' . $this->paramListC($fn) . ')';
        }
        $owner = $fn->ownerClass;
        $params = [$this->cType($owner->code) . '_self'];
        foreach ($fn->params as $param) {
            $params[] = $this->cType($param->type) . ' ' . Names::localVar($param->name);
        }
        return $this->cType($fn->ret) . ' ' . $name . '(' . implode(', ', $params) . ')';
    }

    private function newHelperSignature(ClassSymbol $class): string
    {
        $ctor = $this->effectiveCtor($class);
        $params = $ctor !== null ? $this->paramListC($ctor[0]) : 'void';
        return 'static ' . Names::classStruct($class->name) . '* '
            . Names::newHelper($class->name) . '(' . $params . ')';
    }

    // ------------------------------------------------------------------ 函数体

    /** @param list<array{FnSymbol, array, ?ClassSymbol}> $items */
    private function emitBodies(array $items): void
    {
        $this->begin('funcs');
        $this->indent = 0;
        foreach ($items as [$fn, $body, $class]) {
            $this->curFile = $fn->pos?->file ?? '';
            if ($class === null) {
                $this->genGlobalFn($fn, $body);
            } else {
                $this->genMethod($fn, $body, $class);
            }
        }
        foreach ($this->classesTopo() as $class) {
            $this->curFile = $class->pos?->file ?? '';
            if ($class->isEnum) {
                $this->genEnumMembers($class);
                continue;
            }
            $this->genNewHelper($class);
        }
        // dump 组合函数在正文生成时被发现，这里统一落到 helpers 节
        $this->drainDumps();
    }

    /** 枚举成员生成：case 单例 init、from/tryFrom/cases 合成静态方法。 */
    private function genEnumMembers(ClassSymbol $class): void
    {
        // 合成方法没有自己的 PHP 语句位置，统一回源到枚举声明行——
        // 否则生成代码里的警告会继承上一个 #line 加偏移，报出虚假行号
        $this->curFile = $class->pos?->file ?? $this->curFile;
        $this->sourceLine($class->pos);
        $struct = Names::classStruct($class->name);
        $init = Names::method($class->name, '__enum_init');
        $ready = 'tphp_enum_ready_' . Names::mangle($class->name);
        $this->sections['globals'] .= 'static bool ' . $ready . " = false;\n";
        $this->w('static void ' . $init . '(void)');
        $this->w('{');
        $this->indent = 1;
        $this->w('if (' . $ready . ') {');
        $this->indent = 2;
        $this->w('return;');
        $this->indent = 1;
        $this->w('}');
        foreach ($class->enumCases as $c) {
            $ptr = 'tphp_e_' . Names::mangle($class->name) . '_' . $c['name'];
            $this->w('{');
            $this->indent = 1;
            $this->w($struct . '* o = (' . $struct . '*)tphp_object_alloc_static(sizeof(' . $struct . '), NULL, NULL);');
            $this->w('o->name = ' . $this->strLitExpr($c['name']) . ';');
            if ($class->enumBacking === Type::I_STRING) {
                $v = $c['value'];
                $bytes = $v instanceof \Tphp\Ast\expr\StrLit ? $v->value : '';
                $this->w('o->value = ' . $this->strLitExpr($bytes) . ';');
            } elseif ($class->enumBacking === Type::I_INT) {
                $v = $c['value'];
                $ival = 0;
                if ($v instanceof \Tphp\Ast\expr\IntLit) {
                    $ival = $v->value;
                } elseif ($v instanceof \Tphp\Ast\expr\UnaryExpr && $v->expr instanceof \Tphp\Ast\expr\IntLit) {
                    $ival = -$v->expr->value;
                }
                $this->w('o->value = ' . $ival . ';');
            }
            $this->w($ptr . ' = o;');
            $this->indent = 0;
            $this->w('}');
        }
        $this->w($ready . ' = true;');
        $this->indent = 0;
        $this->w('}');
        $this->w('');

        // case 引用原型（protos 节已声明指针；此处生成 getter 复合表达式由调用点内联）
        // from/tryFrom/cases 合成静态方法
        $this->genEnumFrom($class, true);
        $this->genEnumFrom($class, false);
        $this->genEnumCases($class);
        $this->w('');
    }

    /** from（找不到抛错）/ tryFrom（找不到返回 null）。 */
    private function genEnumFrom(ClassSymbol $class, bool $throwing): void
    {
        if ($class->enumBacking === null || $class->enumCases === []) {
            return;
        }
        $this->sourceLine($class->pos);
        $struct = Names::classStruct($class->name);
        $fn = Names::method($class->name, $throwing ? 'from' : 'tryFrom');
        $init = Names::method($class->name, '__enum_init');
        $backC = $class->enumBacking === Type::I_STRING ? 'String' : 'int32_t';
        $this->w('static ' . $struct . '* ' . $fn . '(' . $backC . ' value)');
        $this->w('{');
        $this->indent = 1;
        $this->w($init . '();');
        $cmp = static fn (string $a, string $b): string => $class->enumBacking === Type::I_STRING
            ? 'tphp_str_eq(' . $a . ', ' . $b . ')'
            : '((' . $a . ') == (' . $b . '))';
        foreach ($class->enumCases as $c) {
            $ptr = 'tphp_e_' . Names::mangle($class->name) . '_' . $c['name'];
            $v = $c['value'];
            $lit = $class->enumBacking === Type::I_STRING
                ? $this->strLitExpr($v instanceof \Tphp\Ast\expr\StrLit ? $v->value : '')
                : (string) ($v instanceof \Tphp\Ast\expr\IntLit ? $v->value
                    : ($v instanceof \Tphp\Ast\expr\UnaryExpr && $v->expr instanceof \Tphp\Ast\expr\IntLit ? -$v->expr->value : 0));
            $this->w('if (' . $cmp('value', $lit) . ') { return ' . $ptr . '; }');
        }
        if ($throwing) {
            $this->w('tphp_err_set(tphp_str_lit("ValueError: not a valid enum value", 33));');
            $this->w('return NULL;');
        } else {
            $this->w('return NULL;');
        }
        $this->indent = 0;
        $this->w('}');
        $this->w('');
    }

    /** cases()：每次调用返回新建数组（owned，调用方持有；单例引用计数不灭）。 */
    private function genEnumCases(ClassSymbol $class): void
    {
        $this->sourceLine($class->pos);
        $struct = Names::classStruct($class->name);
        $init = Names::method($class->name, '__enum_init');
        $fn = Names::method($class->name, 'cases');
        $this->w('static Array* ' . $fn . '(void)');
        $this->w('{');
        $this->indent = 1;
        $this->w($init . '();');
        $this->w('Array* a = tphp_arr_new(sizeof(' . $struct . '*), ' . max(4, count($class->enumCases)) . ', TPHP_ELEM_OBJECT);');
        foreach ($class->enumCases as $c) {
            $ptr = 'tphp_e_' . Names::mangle($class->name) . '_' . $c['name'];
            $this->w('a = tphp_arr_push(a, &' . $ptr . ');');
        }
        $this->w('return a;');
        $this->indent = 0;
        $this->w('}');
        $this->w('');
    }

    /** @param list<object> $body */
    private function genGlobalFn(FnSymbol $fn, array $body): void
    {
        $this->curRet = $fn->ret;
        $this->curClassSym = null;
        $this->sourceLine($fn->pos);
        $this->w($this->cType($fn->ret) . ' ' . $this->fnName($fn->name) . '(' . $this->paramListC($fn) . ')');
        $this->w('{');
        $this->indent = 1;
        $this->rcScopeBegin('function');
        $this->curDepthGuard = $fn->needsDepthGuard;
        if ($this->curDepthGuard) {
            $this->w('tphp_depth_enter();');
        }
        $this->w('size_t __cmem = tphp_cmem_mark();');
        $this->genBoxedParams($fn);
        $this->rcParamIncrefs($fn);
        $this->rcRegisterParams($fn);
        $this->genBodyStmts($body);
        $this->rcCleanupReturn();
        $this->rcScopes = [];
        $this->emitFallbackReturn($fn->ret);
        $this->indent = 0;
        $this->w('}');
        $this->w('');
    }

    private function genMethod(FnSymbol $fn, array $body, ClassSymbol $class): void
    {
        $this->curRet = $fn->ret;
        $this->curClassSym = $class;
        $this->sourceLine($fn->pos);
        $this->w($this->methodSignature($fn, $class));
        $this->w('{');
        $this->indent = 1;
        if (!$fn->isStatic) {
            $owner = $fn->ownerClass;
            $selfType = Names::classStruct($class->name) . '*';
            if ($owner->name === $class->name) {
                $this->w($selfType . ' self = _self;');
            } else {
                $this->w($selfType . ' self = (' . $selfType . ')_self;');
            }
        }
        $this->rcScopeBegin('function');
        $this->curDepthGuard = $fn->needsDepthGuard;
        if ($this->curDepthGuard) {
            $this->w('tphp_depth_enter();');
        }
        $this->w('size_t __cmem = tphp_cmem_mark();');
        $this->genBoxedParams($fn);
        $this->rcParamIncrefs($fn);
        $this->rcRegisterParams($fn);
        $this->genBodyStmts($body);
        $this->rcCleanupReturn();
        $this->rcScopes = [];
        $this->emitFallbackReturn($fn->ret);
        $this->indent = 0;
        $this->w('}');
        $this->w('');
    }

    /** @param list<object> $body */
    private function genBodyStmts(array $body): void
    {
        foreach ($body as $stmt) {
            $this->lastReturned = false;
            $this->genStmt($stmt);
        }
    }

    private function emitFallbackReturn(int $ret): void
    {
        if ($this->lastReturned) {
            return;
        }
        // 函数隐式结束：C 内存出口清理必须执行（void 函数同样需要）
        if ($this->curDepthGuard) {
            $this->w('tphp_depth_leave();');
        }
        $this->w('tphp_cmem_free_since(__cmem);');
        if (!$this->table->isVoid($ret)) {
            $this->w('return ' . $this->zeroValue($ret) . '; /* 不可达兜底 */');
        }
    }

    private function genNewHelper(ClassSymbol $class): void
    {
        $struct = Names::classStruct($class->name);
        $ctor = $this->effectiveCtor($class);
        $this->sourceLine($class->pos);

        // 含堆字段的类生成析构（对象引用计数归零时释放其持有的数组/对象/接口）
        $heapFields = $this->heapFieldsOf($class);
        $dtorName = 'NULL';
        $userDtor = $class->methods['__destruct'] ?? null;
        if ($heapFields !== [] || $userDtor !== null) {
            $dtorName = Names::method($class->name, '__dtor');
            $this->w('static void ' . $dtorName . '(void *p)');
            $this->w('{');
            $this->indent = 1;
            $this->w($struct . ' *self = (' . $struct . ' *)p;');
            if ($userDtor !== null) {
                // 用户析构先于字段释放（PHP 语义）
                $this->w(Names::method($userDtor->ownerClass->name, '__destruct') . '(self);');
            }
            foreach ($heapFields as $field) {
                $this->w($this->fieldUnrefStmt('self->' . $field['name'], $field['type']));
            }
            $this->indent = 0;
            $this->w('}');
            $this->w('');
        }

        $this->w($this->newHelperSignature($class));
        $this->w('{');
        $this->indent = 1;
        $vtInit = $class->vtableOrder !== []
            ? '(void *)&' . Names::vtableInstance($class->name)
            : 'NULL';
        $this->w($struct . ' *self = (' . $struct . ' *)tphp_object_alloc(sizeof(' . $struct . '), '
            . $vtInit . ', ' . $dtorName . ');');

        // 实例属性默认值（含继承来的），按继承深度生成字段路径
        $this->emitPropDefaults($class);

        if ($ctor !== null) {
            [$ctorFn, $ctorOwner] = $ctor;
            $args = ['(' . $this->cType($ctorOwner->code) . ')self'];
            foreach ($ctorFn->params as $param) {
                $args[] = $param->hasDefault
                    ? $this->genExpr($param->default)
                    : Names::localVar($param->name);
            }
            $this->w(Names::method($ctorOwner->name, '__construct') . '(' . implode(', ', $args) . ');');
        }
        $this->w('return self;');
        $this->indent = 0;
        $this->w('}');
        $this->w('');
    }

    /** 类的全部堆字段（含继承，字段已平铺）。 @return list<array{name: string, type: int}> */
    private function heapFieldsOf(ClassSymbol $class): array
    {
        $out = [];
        foreach ($class->props as $prop) {
            if ($prop->isStatic) {
                continue;
            }
            if ($this->isHeapType($prop->type)) {
                $out[] = ['name' => Names::localVar($prop->name), 'type' => $prop->type];
            }
        }
        return $out;
    }

    /** 字段释放语句（数组/对象/接口）。 */
    private function fieldUnrefStmt(string $path, int $type): string
    {
        if ($this->table->isArray($type)) {
            return 'if (' . $path . ') tphp_arr_unref(' . $path . ');';
        }
        if ($this->table->isInterface($type)) {
            return 'if (' . $path . '.obj) tphp_object_unref(' . $path . '.obj);';
        }
        return 'if (' . $path . ') tphp_object_unref(' . $path . ');';
    }

    private function emitPropDefaults(ClassSymbol $class): void
    {
        // 字段已平铺：全部直接访问
        $chain = [];
        for ($c = $class; $c !== null; $c = $c->parent) {
            array_unshift($chain, $c);
        }
        foreach ($chain as $owner) {
            foreach ($owner->props as $prop) {
                if ($prop->isStatic || !$prop->hasDefault) {
                    continue;
                }
                $this->w('self->' . Names::localVar($prop->name) . ' = ' . $this->genExpr($prop->default) . ';');
            }
        }
    }

    // ------------------------------------------------------------------ main

    private function emitMain(): void
    {
        $this->begin('main');
        $main = $this->table->classes['Main'] ?? null;
        $fn = $main?->findMethod('main');
        $ctor = $main !== null ? $this->effectiveCtor($main) : null;
        $needsArgs = $ctor !== null && $ctor[0]->params !== [];
        if ($fn === null) {
            $this->w('int main(void)');
            $this->w('{');
            $this->w('    return 0;');
            $this->w('}');
            return;
        }
        $this->w($needsArgs ? 'int main(int argc, char **argv)' : 'int main(void)');
        $this->w('{');
        // 闭包环境/引用盒子的回收必须先于内存统计（析构会递减捕获的堆引用）
        $this->w('    atexit(tphp_env_free_all);');
        if ($fn->isStatic) {
            $this->w('    ' . Names::method('Main', 'main') . '();');
            $this->w('    if (tphp_err_has()) { tphp_err_uncaught(tphp_err_take()); }');
        } else {
            $ctorArgs = '';
            $arrVar = '';
            if ($needsArgs) {
                $arrVar = 'Array* __args = tphp_args_array(argc, argv);';
                $ctorArgs = 'argc, __args';
            }
            if ($arrVar !== '') {
                $this->w('    ' . $arrVar);
            }
            $this->w('    ' . Names::classStruct('Main') . '* __m = ' . Names::newHelper('Main') . '(' . $ctorArgs . ');');
            if ($arrVar !== '') {
                // 调用方创建引用的释放（形参由构造器自持）
                $this->w('    tphp_arr_unref(__args);');
            }
            $this->w('    ' . Names::method('Main', 'main') . '(__m);');
            $this->w('    tphp_object_unref(__m);');
            $this->w('    if (tphp_err_has()) { tphp_err_uncaught(tphp_err_take()); }');
        }
        $this->w('    return 0;');
        $this->w('}');
    }
}
